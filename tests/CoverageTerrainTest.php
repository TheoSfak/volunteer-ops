<?php

declare(strict_types=1);

use PHPUnit\Framework\TestCase;

/**
 * Verified Coverage measured against the ground (v3.402.0).
 *
 * Before this the percentage used one flat 25 m "a searcher sees this far"
 * radius everywhere, and on synthetic walks it said 84% for a team that walked
 * every street of a city block whose buildings (64% of the ground) nobody
 * entered. The same track must now read differently over open country, over a
 * mountain and over a town, while open country keeps exactly its old numbers.
 *
 * Three layers:
 *  - the pure pieces (terrain choice, turning pings into tracks, sweeping one
 *    polygon) on hand-made data;
 *  - computeMissionSectorCoverage() end to end against the test database, inside
 *    a transaction that is always rolled back;
 *  - source pins for the endpoint action, which needs a signed-in session to run.
 *
 * The sector is a 200 m square at 35.2 N. Metres are turned into degrees with
 * the WGS84 figures for that latitude, not with the 111320 the code under test
 * uses, so the geometry is not generated by the constants it checks.
 */
final class CoverageTerrainTest extends TestCase
{
    private const LAT0 = 35.2000;
    private const LNG0 = 24.9000;
    private const M_PER_DEG_LAT = 110941.0;
    private const M_PER_DEG_LNG = 91288.0;

    private int $missionId;
    private int $shiftId;
    private int $areaId;
    private int $adminId;

    protected function setUp(): void
    {
        db()->beginTransaction();
        $this->adminId = $this->makeUser('Coverage Admin');
        $missionTypeId = (int) dbFetchValue("SELECT id FROM mission_types ORDER BY id LIMIT 1");
        $this->missionId = (int) dbInsert(
            "INSERT INTO missions (title, location, start_datetime, end_datetime, mission_type_id, status, show_in_ops) VALUES (?, ?, ?, ?, ?, ?, 1)",
            ['Coverage Mission', 'Ηράκλειο', date('Y-m-d H:i:s', time() - 7200), date('Y-m-d H:i:s', time() + 7200), $missionTypeId, STATUS_OPEN]
        );
        $this->shiftId = (int) dbInsert(
            "INSERT INTO shifts (mission_id, start_time, end_time) VALUES (?, ?, ?)",
            [$this->missionId, date('Y-m-d H:i:s', time() - 3600), date('Y-m-d H:i:s', time() + 3600)]
        );
        $this->areaId = (int) dbInsert(
            "INSERT INTO mission_search_areas (mission_id, label, geo, created_by) VALUES (?, ?, ?, ?)",
            [$this->missionId, 'Περιοχή', '[]', $this->adminId]
        );
    }

    protected function tearDown(): void
    {
        if (db()->inTransaction()) {
            db()->rollBack();
        }
    }

    // ── helpers ──────────────────────────────────────────────────────────────

    private function makeUser(string $name): int
    {
        return (int) dbInsert(
            "INSERT INTO users (name, email, password) VALUES (?, ?, ?)",
            [$name, 'cov-' . uniqid('', true) . '@example.invalid', 'x']
        );
    }

    /** Metres east/north of the south-west corner, as [lat, lng]. */
    private function at(float $x, float $y): array
    {
        return [self::LAT0 + $y / self::M_PER_DEG_LAT, self::LNG0 + $x / self::M_PER_DEG_LNG];
    }

    private function square(float $size = 200.0): array
    {
        return [$this->at(0, 0), $this->at(0, $size), $this->at($size, $size), $this->at($size, 0)];
    }

    /** One walker's polyline, a fix every $every seconds at walking pace. */
    private function walk(array $polyline, float $every = 20.0, float $speed = 1.3): array
    {
        $fixes = [];
        $t = 0.0;
        for ($i = 0; $i < count($polyline) - 1; $i++) {
            [$x1, $y1] = $polyline[$i];
            [$x2, $y2] = $polyline[$i + 1];
            $duration = hypot($x2 - $x1, $y2 - $y1) / $speed;
            $n = max(1, (int) round($duration / $every));
            for ($k = ($i === 0 ? 0 : 1); $k <= $n; $k++) {
                [$lat, $lng] = $this->at($x1 + ($x2 - $x1) * $k / $n, $y1 + ($y2 - $y1) * $k / $n);
                $fixes[] = ['lat' => $lat, 'lng' => $lng, 'at' => $t + $k * $duration / $n];
            }
            $t += $duration;
        }
        return $fixes;
    }

    /** Lawnmower legs $spacing metres apart across the 200 m square. */
    private function lawnmower(int $spacing): array
    {
        $path = [];
        $up = true;
        for ($x = $spacing / 2; $x < 200; $x += $spacing) {
            $path[] = $up ? [$x, 0] : [$x, 200];
            $path[] = $up ? [$x, 200] : [$x, 0];
            $up = !$up;
        }
        return $path;
    }

    /**
     * Every street of a 200 m square whose four 80 m blocks are buildings, as one
     * walk that never leaves a street (a shortcut would cut a corner of a block).
     */
    private function streets(): array
    {
        return [[5, 5], [195, 5], [195, 195], [5, 195], [5, 5], [5, 100], [195, 100], [100, 100], [100, 5], [100, 195]];
    }

    /** Ping rows as the SELECT in computeMissionSectorCoverage() returns them. */
    private function rows(array $fixes, float $accuracy = 8.0, int $userId = 1): array
    {
        $base = strtotime('2026-10-22 10:00:00');
        return array_map(fn($f) => [
            'user_id' => $userId, 'lat' => $f['lat'], 'lng' => $f['lng'],
            'accuracy_meters' => $accuracy, 'created_at' => date('Y-m-d H:i:s', $base + (int) round($f['at'])),
        ], $fixes);
    }

    private function sweep(array $rows, string $terrain, array $buildings = [], ?array $geo = null): array
    {
        $profile = COVERAGE_TERRAIN_PROFILES[$terrain];
        $tracks = coverageTracksFromPings($rows, $profile['max_gap_s'], $profile['max_accuracy_m']);
        return coverageSweepPolygon($geo ?? $this->square(), $tracks, $profile, $buildings);
    }

    private function insertSector(array $geo, ?string $terrain): int
    {
        dbExecute("UPDATE mission_search_areas SET terrain = ? WHERE id = ?", [$terrain, $this->areaId]);
        return (int) dbInsert(
            "INSERT INTO mission_search_sectors (mission_id, area_id, label, geo, created_by) VALUES (?, ?, ?, ?, ?)",
            [$this->missionId, $this->areaId, 'Τομέας', json_encode($geo), $this->adminId]
        );
    }

    private function insertPings(array $rows): void
    {
        $uid = $this->makeUser('Walker');
        foreach ($rows as $r) {
            dbInsert(
                "INSERT INTO volunteer_pings (user_id, shift_id, lat, lng, accuracy_meters, source, created_at) VALUES (?, ?, ?, ?, ?, 'auto', ?)",
                [$uid, $this->shiftId, $r['lat'], $r['lng'], $r['accuracy_meters'], $r['created_at']]
            );
        }
    }

    // ── the profile table ────────────────────────────────────────────────────

    public function testOpenCountryKeepsItsHistoricalNumbers(): void
    {
        // These four are what every sector was measured with before the ground
        // could be chosen. Changing any of them moves every existing percentage.
        $this->assertSame(
            ['radius_m' => 25, 'max_accuracy_m' => 100, 'max_gap_s' => 1800, 'warn_below' => 60],
            COVERAGE_TERRAIN_PROFILES['rural']
        );
    }

    public function testHarderGroundSeesLessAndTrustsLess(): void
    {
        $rural = COVERAGE_TERRAIN_PROFILES['rural'];
        $mountain = COVERAGE_TERRAIN_PROFILES['mountain'];
        $urban = COVERAGE_TERRAIN_PROFILES['urban'];
        foreach (['radius_m', 'max_accuracy_m', 'max_gap_s', 'warn_below'] as $key) {
            $this->assertGreaterThan($mountain[$key], $rural[$key], $key);
            $this->assertGreaterThan($urban[$key], $mountain[$key], $key);
        }
    }

    // ── which terrain a sector is measured as ────────────────────────────────

    public function testTheAreasChoiceWinsWhateverTheSectorHolds(): void
    {
        $this->assertSame('mountain', coverageEffectiveTerrain('mountain', false));
        $this->assertSame('mountain', coverageEffectiveTerrain('mountain', true));
        $this->assertSame('rural', coverageEffectiveTerrain('rural', true));
        $this->assertSame('urban', coverageEffectiveTerrain('urban', false));
    }

    public function testWithoutAChoiceBuildingsMeanUrbanAndNothingMeansOpenCountry(): void
    {
        $this->assertSame('urban', coverageEffectiveTerrain(null, true));
        $this->assertSame('rural', coverageEffectiveTerrain(null, false));
        // A value the table does not know falls back instead of failing.
        $this->assertSame('rural', coverageEffectiveTerrain('swamp', false));
        $this->assertSame('urban', coverageEffectiveTerrain('swamp', true));
    }

    // ── pings into tracks ────────────────────────────────────────────────────

    public function testAFixVaguerThanTheGroundAllowsIsNotBelieved(): void
    {
        $rows = $this->rows($this->walk([[10, 10], [190, 10]]), 45.0);
        $rural = coverageTracksFromPings($rows, 1800, 100);
        $mountain = coverageTracksFromPings($rows, 300, 50);
        $urban = coverageTracksFromPings($rows, 120, 30);
        $this->assertNotEmpty($rural['points']);
        $this->assertNotEmpty($mountain['points']);
        $this->assertSame([], $urban['points']);
        $this->assertSame([], $urban['segments']);
    }

    public function testAFixWithNoAccuracyAtAllIsStillUsed(): void
    {
        $rows = $this->rows($this->walk([[10, 10], [190, 10]]));
        foreach ($rows as &$r) {
            $r['accuracy_meters'] = null;
        }
        unset($r);
        $this->assertNotEmpty(coverageTracksFromPings($rows, 120, 30)['points']);
    }

    public function testASilenceLongerThanTheGroundAllowsIsNotDrawnAsAWalkedLine(): void
    {
        // Two fixes 1 km apart, ten minutes apart.
        $rows = [
            ['user_id' => 1, 'lat' => self::LAT0, 'lng' => self::LNG0, 'accuracy_meters' => 8, 'created_at' => '2026-10-22 10:00:00'],
            ['user_id' => 1, 'lat' => self::LAT0 + 1000 / self::M_PER_DEG_LAT, 'lng' => self::LNG0, 'accuracy_meters' => 8, 'created_at' => '2026-10-22 10:10:00'],
        ];
        $this->assertCount(1, coverageTracksFromPings($rows, 1800, 100)['segments'], 'open country draws it');
        $this->assertCount(0, coverageTracksFromPings($rows, 300, 50)['segments'], 'a mountain does not');
        $this->assertCount(0, coverageTracksFromPings($rows, 120, 30)['segments'], 'a town does not');
    }

    public function testASegmentNeverJoinsTwoDifferentPeople(): void
    {
        $rows = [
            ['user_id' => 1, 'lat' => self::LAT0, 'lng' => self::LNG0, 'accuracy_meters' => 8, 'created_at' => '2026-10-22 10:00:00'],
            ['user_id' => 2, 'lat' => self::LAT0 + 50 / self::M_PER_DEG_LAT, 'lng' => self::LNG0, 'accuracy_meters' => 8, 'created_at' => '2026-10-22 10:00:10'],
        ];
        $this->assertSame([], coverageTracksFromPings($rows, 1800, 100)['segments']);
    }

    // ── one polygon ──────────────────────────────────────────────────────────

    public function testNobodyWalkingIsZeroNotMissing(): void
    {
        $swept = $this->sweep([], 'urban');
        $this->assertSame(0, $swept['percent']);
        $this->assertGreaterThan(0, $swept['total_cells']);
    }

    public function testTheSameWalkIsLessCoverageWhereAWalkerSeesLess(): void
    {
        $rows = $this->rows($this->walk($this->lawnmower(50)));
        $rural = $this->sweep($rows, 'rural')['percent'];
        $mountain = $this->sweep($rows, 'mountain')['percent'];
        $urban = $this->sweep($rows, 'urban')['percent'];

        // Legs 50 m apart: a 50 m swath tiles the square, a 30 m one covers about
        // 60% of it and a 20 m one about 40%.
        $this->assertGreaterThanOrEqual(98, $rural);
        $this->assertEqualsWithDelta(60, $mountain, 8);
        $this->assertEqualsWithDelta(40, $urban, 8);
    }

    public function testStreetsWalkedIsNoLongerCalledAWholeCityBlock(): void
    {
        $rows = $this->rows($this->walk($this->streets()));
        $asOpenCountry = $this->sweep($rows, 'rural')['percent'];
        $asTown = $this->sweep($rows, 'urban')['percent'];

        // What v3.401 reported for this walk: the radius reached through the
        // walls into buildings nobody entered.
        $this->assertGreaterThanOrEqual(80, $asOpenCountry);
        $this->assertLessThanOrEqual(60, $asTown);
        $this->assertGreaterThan(COVERAGE_TERRAIN_PROFILES['urban']['warn_below'], $asTown,
            'a town walked street by street must not look unfinished');
    }

    public function testOnlyTheOuterStreetWalkedStillLooksUnfinishedInATown(): void
    {
        $rows = $this->rows($this->walk([[5, 5], [195, 5], [195, 195], [5, 195], [5, 5]]));
        $percent = $this->sweep($rows, 'urban')['percent'];
        $this->assertLessThan(COVERAGE_TERRAIN_PROFILES['urban']['warn_below'] + 5, $percent);
    }

    public function testGroundInsideARegisteredBuildingIsLeftOutOfBothCounts(): void
    {
        $rows = $this->rows($this->walk($this->streets()));
        $bare = $this->sweep($rows, 'urban');
        // Houses at the centre of each 100 m cell, between the streets.
        $houses = [$this->at(50, 50), $this->at(150, 50), $this->at(50, 150), $this->at(150, 150)];
        $registered = $this->sweep($rows, 'urban', $houses);

        $this->assertSame(0, $bare['excluded_cells']);
        $this->assertGreaterThan(0, $registered['excluded_cells']);
        $this->assertSame(
            $bare['total_cells'],
            $registered['total_cells'] + $registered['excluded_cells'],
            'every cell is either counted or excluded, none disappears'
        );
        // The streets are far from the house centres, so nothing excluded was covered:
        // the same covered cells over a smaller denominator can only rise.
        $this->assertSame($bare['covered_cells'], $registered['covered_cells']);
        $this->assertGreaterThanOrEqual($bare['percent'], $registered['percent']);
    }

    public function testAWalkedLineThroughARegisteredBuildingDoesNotCoverIt(): void
    {
        // The walker goes straight over the house point, as a GPS track through a
        // wall would. The ground there is excluded, not credited.
        $rows = $this->rows($this->walk([[10, 100], [190, 100]]));
        $house = [$this->at(100, 100)];
        $without = $this->sweep($rows, 'rural');
        $with = $this->sweep($rows, 'rural', $house);
        $this->assertLessThan($without['covered_cells'], $with['covered_cells']);
        $this->assertGreaterThan(0, $with['excluded_cells']);
    }

    // ── the whole mission, from the database ─────────────────────────────────

    public function testEachSectorIsMeasuredAsItsAreasTerrain(): void
    {
        $sectorId = $this->insertSector($this->square(), 'mountain');
        $this->insertPings($this->rows($this->walk($this->lawnmower(50))));

        $entry = computeMissionSectorCoverage($this->missionId)[$sectorId];
        $this->assertSame('mountain', $entry['terrain']);
        $this->assertSame(15, $entry['radius_m']);
        $this->assertSame(45, $entry['warn_below']);
        $this->assertEqualsWithDelta(60, $entry['percent'], 8);

        dbExecute("UPDATE mission_search_areas SET terrain = 'rural' WHERE id = ?", [$this->areaId]);
        $rural = computeMissionSectorCoverage($this->missionId)[$sectorId];
        $this->assertSame('rural', $rural['terrain']);
        $this->assertGreaterThanOrEqual(98, $rural['percent']);
    }

    public function testAnAreaWithNoChoiceMeasuresAsOpenCountryLikeBefore(): void
    {
        $sectorId = $this->insertSector($this->square(), null);
        $this->insertPings($this->rows($this->walk($this->lawnmower(50))));

        $entry = computeMissionSectorCoverage($this->missionId)[$sectorId];
        $this->assertSame('rural', $entry['terrain']);
        $this->assertGreaterThanOrEqual(98, $entry['percent']);
    }

    public function testASectorWithRegisteredBuildingsIsUrbanUnlessTheAreaSaysOtherwise(): void
    {
        $sectorId = $this->insertSector($this->square(), null);
        [$lat, $lng] = $this->at(100, 100);
        dbInsert(
            "INSERT INTO mission_sector_buildings (sector_id, label, lat, lng, floor_count, created_by) VALUES (?, ?, ?, ?, 2, ?)",
            [$sectorId, 'Κτίριο', $lat, $lng, $this->adminId]
        );
        $this->insertPings($this->rows($this->walk($this->streets())));

        $this->assertSame('urban', computeMissionSectorCoverage($this->missionId)[$sectorId]['terrain']);

        dbExecute("UPDATE mission_search_areas SET terrain = 'mountain' WHERE id = ?", [$this->areaId]);
        $this->assertSame('mountain', computeMissionSectorCoverage($this->missionId)[$sectorId]['terrain']);
    }

    public function testAVagueFixIsBelievedInOpenCountryAndNotInATown(): void
    {
        $sectorId = $this->insertSector($this->square(), 'rural');
        $this->insertPings($this->rows($this->walk($this->lawnmower(50)), 60.0));
        $this->assertGreaterThanOrEqual(98, computeMissionSectorCoverage($this->missionId)[$sectorId]['percent']);

        dbExecute("UPDATE mission_search_areas SET terrain = 'urban' WHERE id = ?", [$this->areaId]);
        $this->assertSame(0, computeMissionSectorCoverage($this->missionId)[$sectorId]['percent']);
    }

    public function testTwoAreasOnOneMissionAreMeasuredEachAsItsOwn(): void
    {
        $field = $this->insertSector($this->square(), 'rural');
        $otherArea = (int) dbInsert(
            "INSERT INTO mission_search_areas (mission_id, label, geo, terrain, created_by) VALUES (?, ?, '[]', 'urban', ?)",
            [$this->missionId, 'Χωριό', $this->adminId]
        );
        $town = (int) dbInsert(
            "INSERT INTO mission_search_sectors (mission_id, area_id, label, geo, created_by) VALUES (?, ?, ?, ?, ?)",
            [$this->missionId, $otherArea, 'Τομέας Β', json_encode($this->square()), $this->adminId]
        );
        $this->insertPings($this->rows($this->walk($this->lawnmower(50))));

        $result = computeMissionSectorCoverage($this->missionId);
        $this->assertSame('rural', $result[$field]['terrain']);
        $this->assertSame('urban', $result[$town]['terrain']);
        $this->assertGreaterThan($result[$town]['percent'], $result[$field]['percent']);
    }

    public function testAMissionWithNoSectorsHasNoCoverage(): void
    {
        $this->assertSame([], computeMissionSectorCoverage($this->missionId));
    }

    // ── the endpoint and the page, as source pins ────────────────────────────

    public function testSettingTheTerrainIsCommandOnly(): void
    {
        $source = file_get_contents(__DIR__ . '/../mission-sector.php');
        $gate = strpos($source, 'Everything below requires admin');
        $action = strpos($source, "\$action === 'set_area_terrain'");
        $this->assertNotFalse($gate);
        $this->assertNotFalse($action);
        $this->assertGreaterThan($gate, $action, 'set_area_terrain must sit below the admin gate');
        $this->assertStringContainsString('COVERAGE_TERRAIN_PROFILES[$terrainRaw]', $source,
            'the value must be checked against the profile table, never trusted');
    }

    public function testTheAreaPayloadCarriesTheTerrain(): void
    {
        dbExecute("UPDATE mission_search_areas SET terrain = 'urban' WHERE id = ?", [$this->areaId]);
        $areas = loadMissionSearchAreasForUser($this->missionId, true);
        $this->assertCount(1, $areas);
        $this->assertSame('urban', $areas[0]['terrain']);

        dbExecute("UPDATE mission_search_areas SET terrain = NULL WHERE id = ?", [$this->areaId]);
        $this->assertNull(loadMissionSearchAreasForUser($this->missionId, true)[0]['terrain']);
    }

    public function testBothLanguagesNameEveryTerrain(): void
    {
        $strings = loadLangStrings('war-room');
        foreach (['el', 'en'] as $lang) {
            foreach (['auto', 'rural', 'mountain', 'urban'] as $key) {
                $this->assertArrayHasKey('coverage.terrain.' . $key, $strings[$lang], "$lang coverage.terrain.$key");
            }
            foreach (['coverage.basis', 'coverage.terrain_label', 'coverage.terrain_hint'] as $key) {
                $this->assertArrayHasKey($key, $strings[$lang], "$lang $key");
            }
        }
    }
